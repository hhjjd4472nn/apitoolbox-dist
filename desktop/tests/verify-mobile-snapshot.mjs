import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import {initialState} from '../src/core/state.mjs';
import {SecretStore} from '../src/core/secret-store.mjs';
import {importMobileSnapshot} from '../src/core/full-sync.mjs';
const file=process.argv[2] || '/sdcard/tiany/v132/v159/snapshot159.json';
const raw=fs.readFileSync(file,'utf8');
const payload=JSON.parse(raw);
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'atb-v2-import-'));
const adapter={available:()=>true,encrypt:value=>Buffer.from(`sealed:${value.toString('base64')}`),decrypt:value=>Buffer.from(value.toString().slice(7),'base64')};
const secrets=new SecretStore(path.join(dir,'secrets.bin'),adapter);
const result=importMobileSnapshot(payload,'123456',initialState(),secrets,raw);
assert.equal(result.imported.length,9);
assert.equal(result.state.modules.length,9);
assert.ok(result.imported.every(account=>account.credentialRef&&secrets.get(account.credentialRef)));
assert.equal(JSON.stringify(result.state).includes('KP_SECRET'),false);
assert.equal(JSON.stringify(result.state).includes('fixed-secret'),false);
const prefRefs=Object.values(result.state.mobileGroups).flatMap(group=>Object.values(group||{})).filter(value=>value?.credentialRef);
assert.ok(prefRefs.length>=2);
console.log(`DESKTOP_IMPORT159_OK accounts=${result.imported.length} modules=${result.state.modules.length} secret_refs=${result.imported.length+prefRefs.length}`);